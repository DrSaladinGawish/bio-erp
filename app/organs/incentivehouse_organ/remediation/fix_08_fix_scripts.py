#!/usr/bin/env python3
"""FIX 8 (P1): Create fix_broken_imports.py and fix_all_tables.py utility scripts"""

import sys
import pathlib

BASE = pathlib.Path(r"D:\ERP System\BIO_ERP")
IH = BASE / "app" / "organs" / "incentivehouse_organ"
DRY = "--dry-run" in sys.argv

print("FIX 8: Create utility fix scripts (fix_broken_imports.py + fix_all_tables.py)")

FIX_IMPORTS = '''#!/usr/bin/env python3
"""Fix broken imports across the IH organ (audit fix 12.1).
Auto-generated by remediation/fix_08_fix_scripts.py
"""
import re, pathlib, sys

IH = pathlib.Path(__file__).parent

# Map of old -> new module paths
REPLACEMENTS = [
    (r"from app\\.incentivehouse\\.", "from app.organs.incentivehouse_organ."),
    (r"from app\\.or_module\\.", "from app.organs.or_organ."),
    (r"from app\\.ih_module\\.", "from app.organs.incentivehouse_organ."),
    (r"from\\s+app\\.models\\s+import", "from app.organs.incentivehouse_organ.models import"),
    (r"import app\\.models\\b", "import app.organs.incentivehouse_organ.models"),
]

def main():
    fixed = 0
    files = list(IH.rglob("*.py"))
    for p in files:
        if p.name in ("fix_broken_imports.py", "fix_all_tables.py"):
            continue
        try:
            src = p.read_text(encoding="utf-8", errors="ignore")
        except Exception:
            continue
        new = src
        for pat, rep in REPLACEMENTS:
            new = re.sub(pat, rep, new)
        if new != src:
            p.write_text(new, encoding="utf-8")
            print(f"  fixed: {p.relative_to(IH)}")
            fixed += 1
    print(f"Done. {fixed} files updated.")

if __name__ == "__main__":
    main()
'''

